func genRepeatedUnmarshal(g *protogen.GeneratedFile, field *protogen.Field) {
	goName := field.GoName
	kind := field.Desc.Kind()

	if isScalar(field) {
		g.P("if wireType == 2 {")
		g.P("length, n, err := protowire.DecodeVarint(data[i:]); if err != nil { return nil, err }; i += n")
		g.P("end := i + int(length)")
		g.P("for i < end {")
		genScalarDecode(g, field)
		g.P("m.", goName, " = arena.Append(ar, m.", goName, ", ", castVal(field), ")")
		g.P("}")
		g.P("} else {")
		genScalarDecode(g, field)
		g.P("m.", goName, " = arena.Append(ar, m.", goName, ", ", castVal(field), ")")
		g.P("}")
	} else if kind == protoreflect.StringKind {
		g.P("length, n, err := protowire.DecodeVarint(data[i:]); if err != nil { return nil, err }; i += n")
		g.P("m.", goName, " = arena.Append(ar, m.", goName, ", protowire.String(ar, data[i:i+int(length)]))")
		g.P("i += int(length)")
	} else if kind == protoreflect.BytesKind {
		g.P("length, n, err := protowire.DecodeVarint(data[i:]); if err != nil { return nil, err }; i += n")
		g.P("m.", goName, " = arena.Append(ar, m.", goName, ", ar.Bytes(data[i:i+int(length)]))")
		g.P("i += int(length)")
	} else if kind == protoreflect.MessageKind {
		g.P("msgLen, n, err := protowire.DecodeVarint(data[i:]); if err != nil { return nil, err }; i += n")
		g.P("msg, err := Unmarshal", field.Message.GoIdent.GoName, "(data[i:i+int(msgLen)], ar)")
		g.P("if err != nil { return nil, err }")
		g.P("m.", goName, " = arena.Append(ar, m.", goName, ", msg)")
		g.P("i += int(msgLen)")
	}
}

func genScalarDecode(g *protogen.GeneratedFile, field *protogen.Field) {
	kind := field.Desc.Kind()
	switch {
	case kind == protoreflect.Fixed32Kind || kind == protoreflect.Sfixed32Kind || kind == protoreflect.FloatKind:
		g.P("val, n, err := protowire.DecodeFixed32(data[i:]); if err != nil { return nil, err }; i += n")
	case kind == protoreflect.Fixed64Kind || kind == protoreflect.Sfixed64Kind || kind == protoreflect.DoubleKind:
		g.P("val, n, err := protowire.DecodeFixed64(data[i:]); if err != nil { return nil, err }; i += n")
	default:
		g.P("val, n, err := protowire.DecodeVarint(data[i:]); if err != nil { return nil, err }; i += n")
	}
}

func castVal(field *protogen.Field) string {
	kind := field.Desc.Kind()
	switch kind {
	case protoreflect.Int32Kind:
		return "int32(val)"
	case protoreflect.Int64Kind:
		return "int64(val)"
	case protoreflect.Uint32Kind:
		return "uint32(val)"
	case protoreflect.Uint64Kind:
		return "uint64(val)"
	case protoreflect.Sint32Kind:
		return "int32(protowire.DecodeZigZag(val))"
	case protoreflect.Sint64Kind:
		return "protowire.DecodeZigZag(val)"
	case protoreflect.BoolKind:
		return "val != 0"
	case protoreflect.EnumKind:
		return string(field.Enum.GoIdent.GoName) + "(val)"
	case protoreflect.FloatKind:
		return "math.Float32frombits(val)"
	case protoreflect.DoubleKind:
		return "math.Float64frombits(val)"
	case protoreflect.Sfixed32Kind:
		return "int32(val)"
	case protoreflect.Sfixed64Kind:
		return "int64(val)"
	default:
		return "val"
	}
}
