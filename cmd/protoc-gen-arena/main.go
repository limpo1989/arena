func genUnmarshal(g *protogen.GeneratedFile, msg *protogen.Message) {
	g.P("func Unmarshal", msg.GoIdent.GoName, "(data []byte, ar *arena.Arena) (*", msg.GoIdent.GoName, ", error) {")
	g.P("m := arena.New[", msg.GoIdent.GoName, "](ar)")
	g.P("i := 0")
	g.P("for i < len(data) {")
	g.P("tag, n, err := protowire.DecodeVarint(data[i:])")
	g.P("if err != nil { return nil, err }")
	g.P("i += n")
	g.P("fieldNum := int(tag >> 3)")
	g.P("wireType := int(tag & 7)")
	g.P("switch fieldNum {")
	for _, field := range msg.Fields {
		genFieldUnmarshalCase(g, msg, field)
	}
	g.P("default:")
	g.P("skipped, err := protowire.SkipField(data[i:], wireType)")
	g.P("if err != nil { return nil, err }")
	g.P("i += skipped")
	g.P("}")
	g.P("}")
	for _, field := range msg.Fields {
		if field.Desc.Cardinality() == protoreflect.Required {
			g.P("if m.", field.GoName, " == nil { return nil, fmt.Errorf(\"proto: required field '", field.Desc.Name(), "' not set\") }")
		}
	}
	g.P("return m, nil")
	g.P("}")
	g.P()
}

